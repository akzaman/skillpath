const TABLES: Record<Locale, Dict> = { en, it, bn };

const CATEGORY_KEY: Record<Category, string> = {
  "Fisco e tasse": "cat.tax",
  "CAF e Patronato": "cat.caf",
  "Lingua italiana": "cat.lang",
  "Patente B": "cat.license",
  Immigrazione: "cat.immigration",
  "Lavoro e impresa": "cat.work",
};

const LEVEL_KEY: Record<Level, string> = {
  Foundations: "level.foundations",
  Intermediate: "level.intermediate",
  Advanced: "level.advanced",
};

function interpolate(template: string, vars?: Record<string, string | number>) {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? `{${key}}`));
}

function detectLocale(): Locale {
  if (typeof window === "undefined") return "en";
  try {
    const saved = window.localStorage.getItem(STORAGE);
    if (saved === "en" || saved === "it" || saved === "bn") return saved;
  } catch {
    /* ignore */
  }
  const nav = (navigator.language || "en").toLowerCase();
  if (nav.startsWith("it")) return "it";
  if (nav.startsWith("bn")) return "bn";
  return "en";
}

type I18nValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
  category: (value: string) => string;
  level: (value: string) => string;
};

const I18nContext = createContext<I18nValue | null>(null);

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("en");

  useEffect(() => {
    setLocaleState(detectLocale());
  }, []);

  useEffect(() => {
    document.documentElement.lang = locale;
    document.documentElement.classList.toggle("locale-bn", locale === "bn");
    try {
      window.localStorage.setItem(STORAGE, locale);
    } catch {
      /* ignore */
    }
  }, [locale]);

  const value = useMemo<I18nValue>(() => {
    const table = TABLES[locale];
    const t = (key: string, vars?: Record<string, string | number>) =>
      interpolate(table[key] ?? TABLES.en[key] ?? key, vars);
    return {
      locale,
      setLocale: setLocaleState,
      t,
      category: (value) => t(CATEGORY_KEY[value as Category] ?? value),
      level: (value) => t(LEVEL_KEY[value as Level] ?? value),
    };
  }, [locale]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const ctx = useContext(I18nContext);
  if (!ctx) {
    const t = (key: string, vars?: Record<string, string | number>) =>
      interpolate(TABLES.en[key] ?? key, vars);
    return {
      locale: "en",
      setLocale: () => undefined,
      t,
      category: (value) => t(CATEGORY_KEY[value as Category] ?? value),
      level: (value) => t(LEVEL_KEY[value as Level] ?? value),
    };
  }
  return ctx;
}
